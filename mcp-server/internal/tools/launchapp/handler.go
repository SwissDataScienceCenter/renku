// Package launchapp is the launch_app tool.
package launchapp

import (
	"context"

	"github.com/modelcontextprotocol/go-sdk/mcp"

	"github.com/SwissDataScienceCenter/renku/mcp-server/internal/renkuapi"
	"github.com/SwissDataScienceCenter/renku/mcp-server/internal/renkuapi/renkuapps"
	"github.com/SwissDataScienceCenter/renku/mcp-server/internal/tools/toolkit"
)

var tool = mcp.Tool{
	Name: "launch_app",
	Description: "Launch an app: a long-running deployment of a project, served publicly to anonymous " +
		"visitors. It runs a launcher created with `launcher_type` `app`.\n\n" +
		"- The project must be public. If it is not, tell the user and let them decide; never change " +
		"the visibility for them.\n" +
		"- A project can have only one app. Check with list_apps first; if the user wants to replace " +
		"the existing app, delete it with delete_app.\n" +
		"- The app name is generated by Renku, so take it from the response, never build it.\n" +
		"- Only public data connectors that need no credentials are mounted. Tell the user if they " +
		"expect private data in the app.\n\n" +
		"Then call wait_for_app until the status is `ready` or `failed`.",
	Annotations: &mcp.ToolAnnotations{DestructiveHint: new(false)},
}

type input struct {
	LauncherID string `json:"launcher_id" jsonschema:"The ID of a session launcher whose launcher_type is app, a ULID."`
}

func handler(api *renkuapi.Clients) mcp.ToolHandlerFor[input, any] {
	return func(ctx context.Context, req *mcp.CallToolRequest, in input) (*mcp.CallToolResult, any, error) {
		res, err := api.RenkuApps.PostAppsWithResponse(ctx, renkuapps.AppPostRequest{LauncherId: in.LauncherID}, toolkit.CallerHeaders(ctx, req))
		if err != nil {
			return nil, nil, toolkit.RequestFailed(err)
		}
		if res.JSON201 == nil {
			return nil, nil, toolkit.APIError(res.StatusCode(), res.Body)
		}
		return nil, res.JSON201, nil
	}
}

// Register adds the tool to the mcp server.
func Register(s *mcp.Server, api *renkuapi.Clients) {
	mcp.AddTool(s, &tool, handler(api))
}
