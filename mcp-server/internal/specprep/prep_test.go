func TestPrepareErrors(t *testing.T) {
	modules := map[string][]byte{"projects.yaml": []byte(projectsModule), "sessions.yaml": []byte(sessionsModule)}
	tests := []struct {
		name string
		tool Tool
		want string
	}{
		{"unknown operation", Tool{Method: "delete", Path: "/projects", Name: "delete_projects", Description: "x"}, "operation not found"},
		{"unknown parameter override", Tool{Method: "get", Path: "/sessions", Name: "list_sessions", Description: "x", Parameters: map[string]string{"nope": "x"}}, `parameter override "nope"`},
		{"invalid name", Tool{Method: "get", Path: "/sessions", Name: "ListSessions", Description: "x"}, "must match"},
		{"missing description", Tool{Method: "get", Path: "/sessions", Name: "list_sessions"}, "description is required"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := Prepare(testConfig(tt.tool), "v1", modules)
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("expected error containing %q, got %v", tt.want, err)
			}
		})
	}
}
