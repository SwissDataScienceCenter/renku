package specprep

import (
	"bytes"
	"fmt"
	"reflect"
	"slices"
	"sort"
	"strings"

	"github.com/pb33f/libopenapi"
	"sigs.k8s.io/yaml"
)

const componentRefPrefix = "#/components/"

type module struct {
	name string
	doc  map[string]any
}

type componentKey struct {
	kind string
	name string
}

func (k componentKey) String() string { return k.kind + "/" + k.name }

type preparer struct {
	modules    []*module
	components map[componentKey]any
	origin     map[componentKey]string
	// visited tracks which module's definition of a component has been walked,
	// so identical components still have their own references checked.
	visited map[string]bool
}

// Prepare builds the pruned OpenAPI document for the allowlisted tools.
// modules maps each path in cfg.Source.Modules to the raw content of that spec.
// ref is the git ref the modules were taken from and is recorded in the output.
func Prepare(cfg *Config, ref string, modules map[string][]byte) ([]byte, error) {
	if err := cfg.Validate(); err != nil {
		return nil, err
	}
	p := &preparer{
		components: map[componentKey]any{},
		origin:     map[componentKey]string{},
		visited:    map[string]bool{},
	}
	var openapiVersion, serverURL string
	for _, name := range cfg.Source.Modules {
		raw, ok := modules[name]
		if !ok {
			return nil, fmt.Errorf("module %s was not provided", name)
		}
		var doc map[string]any
		if err := yaml.Unmarshal(raw, &doc); err != nil {
			return nil, fmt.Errorf("parsing module %s: %w", name, err)
		}
		version, _ := doc["openapi"].(string)
		if !strings.HasPrefix(version, "3.0.") {
			return nil, fmt.Errorf("module %s: only OpenAPI 3.0.x is supported, got %q", name, version)
		}
		url := moduleServerURL(doc)
		if openapiVersion == "" {
			openapiVersion, serverURL = version, url
		} else if url != serverURL {
			return nil, fmt.Errorf("module %s: server url %q differs from %q", name, url, serverURL)
		}
		p.modules = append(p.modules, &module{name: name, doc: doc})
	}

	paths := map[string]any{}
	for _, t := range cfg.Tools {
		op, err := p.operation(t)
		if err != nil {
			return nil, fmt.Errorf("tool %s (%s %s): %w", t.Name, t.Method, t.Path, err)
		}
		item, _ := paths[t.Path].(map[string]any)
		if item == nil {
			item = map[string]any{}
			paths[t.Path] = item
		}
		item[t.Method] = op
	}

	components := map[string]any{}
	for key, def := range p.components {
		kind, _ := components[key.kind].(map[string]any)
		if kind == nil {
			kind = map[string]any{}
			components[key.kind] = kind
		}
		kind[key.name] = def
	}

	out := map[string]any{
		"openapi": openapiVersion,
		"info": map[string]any{
			"title":       "Renku Data Services API (MCP subset)",
			"description": "Allowlisted subset of the Renku Data Services API exposed through the Renku MCP server.",
			"version":     ref,
		},
		"servers": []any{map[string]any{"url": serverURL}},
		"paths":   paths,
	}
	if len(components) > 0 {
		out["components"] = components
	}
	// mcpgen embeds descriptions and schemas in Go raw string literals, which cannot contain backticks.
	body, err := yaml.Marshal(replaceStrings(out, func(s string) string { return strings.ReplaceAll(s, "`", "'") }))
	if err != nil {
		return nil, err
	}
	if err := validate(body); err != nil {
		return nil, err
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# Code generated by specprep from %s@%s. DO NOT EDIT.\n", cfg.Source.Repository, ref)
	buf.WriteString("# Edit apispec/tools.yaml and run 'just update-spec <ref>' instead.\n")
	buf.Write(body)
	return buf.Bytes(), nil
}

func moduleServerURL(doc map[string]any) string {
	servers, _ := doc["servers"].([]any)
	if len(servers) == 0 {
		return ""
	}
	server, _ := servers[0].(map[string]any)
	url, _ := server["url"].(string)
	return url
}

// validate checks that the result is a well-formed OpenAPI 3 document.
func validate(body []byte) error {
	doc, err := libopenapi.NewDocument(body)
	if err != nil {
		return fmt.Errorf("generated spec is not a valid OpenAPI document: %w", err)
	}
	if _, err := doc.BuildV3Model(); err != nil {
		return fmt.Errorf("generated spec is not a valid OpenAPI 3 document: %w", err)
	}
	return nil
}

func (p *preparer) operation(t Tool) (map[string]any, error) {
	var mod *module
	var pathItem map[string]any
	for _, m := range p.modules {
		paths, _ := m.doc["paths"].(map[string]any)
		item, _ := paths[t.Path].(map[string]any)
		if _, ok := item[t.Method]; !ok {
			continue
		}
		if mod != nil {
			return nil, fmt.Errorf("operation is defined in both %s and %s", mod.name, m.name)
		}
		mod, pathItem = m, item
	}
	if mod == nil {
		return nil, fmt.Errorf("operation not found in any module")
	}
	op, ok := deepCopy(pathItem[t.Method]).(map[string]any)
	if !ok {
		return nil, fmt.Errorf("operation is not an object")
	}

	params, err := p.parameters(mod, pathItem["parameters"], op["parameters"])
	if err != nil {
		return nil, err
	}
	for name, description := range t.Parameters {
		found := false
		for _, param := range params {
			if param.(map[string]any)["name"] == name {
				param.(map[string]any)["description"] = description
				found = true
			}
		}
		if !found {
			return nil, fmt.Errorf("parameter override %q does not match any parameter", name)
		}
	}
	if len(params) > 0 {
		op["parameters"] = params
	} else {
		delete(op, "parameters")
	}

	responses, err := p.stripResponses(mod, op["responses"])
	if err != nil {
		return nil, err
	}
	op["responses"] = responses

	op["operationId"] = t.Name
	// mcpgen embeds the operation description in an interpreted Go string literal.
	op["description"] = strings.NewReplacer(`"`, "'", `\`, "/", "\n", " ").Replace(strings.TrimSpace(t.Description))
	delete(op, "summary")

	if err := p.collectRefs(mod, op); err != nil {
		return nil, err
	}
	return op, nil
}

// stripResponses keeps only the description of each response. mcpgen renders
// response schemas into templates in random order, which would make the
// generated code differ on every run, and the tools forward the raw JSON
// responses anyway.
func (p *preparer) stripResponses(mod *module, v any) (map[string]any, error) {
	responses, _ := v.(map[string]any)
	out := map[string]any{}
	for status, r := range responses {
		response, _ := r.(map[string]any)
		if ref, ok := response["$ref"].(string); ok {
			key, err := parseRef(ref)
			if err != nil {
				return nil, err
			}
			def, found := lookup(mod, key)
			if !found {
				return nil, fmt.Errorf("%s: %s not found", mod.name, ref)
			}
			response, _ = def.(map[string]any)
		}
		description, _ := response["description"].(string)
		out[status] = map[string]any{"description": description}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("operation has no responses")
	}
	return out, nil
}

// parameters merges path level and operation level parameters, inlines
// parameter references and flattens exploded object query parameters, because
// mcpgen only looks at inline operation level parameters.
func (p *preparer) parameters(mod *module, pathLevel, opLevel any) ([]any, error) {
	var merged []map[string]any
	for _, list := range []any{pathLevel, opLevel} {
		items, _ := deepCopy(list).([]any)
		for _, item := range items {
			param, err := p.resolveParameter(mod, item)
			if err != nil {
				return nil, err
			}
			// Operation level parameters override path level ones with the same name and location.
			merged = slices.DeleteFunc(merged, func(m map[string]any) bool {
				return m["name"] == param["name"] && m["in"] == param["in"]
			})
			merged = append(merged, param)
		}
	}
	var result []any
	for _, param := range merged {
		flat, err := p.flattenQueryObject(mod, param)
		if err != nil {
			return nil, fmt.Errorf("parameter %v: %w", param["name"], err)
		}
		result = append(result, flat...)
	}
	return result, nil
}

func (p *preparer) resolveParameter(mod *module, item any) (map[string]any, error) {
	param, ok := item.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("parameter is not an object")
	}
	ref, ok := param["$ref"].(string)
	if !ok {
		return param, nil
	}
	key, err := parseRef(ref)
	if err != nil {
		return nil, err
	}
	if key.kind != "parameters" {
		return nil, fmt.Errorf("parameter reference %s does not point to a parameter", ref)
	}
	def, ok := lookup(mod, key)
	if !ok {
		return nil, fmt.Errorf("%s: %s not found", mod.name, ref)
	}
	return p.resolveParameter(mod, deepCopy(def))
}

// flattenQueryObject turns a form-exploded object query parameter into one
// parameter per property, which is equivalent on the wire.
func (p *preparer) flattenQueryObject(mod *module, param map[string]any) ([]any, error) {
	if param["in"] != "query" {
		return []any{param}, nil
	}
	if style, ok := param["style"].(string); ok && style != "form" {
		return []any{param}, nil
	}
	if explode, ok := param["explode"].(bool); ok && !explode {
		return []any{param}, nil
	}
	props, required, ok, err := p.objectProperties(mod, param["schema"])
	if err != nil || !ok {
		return []any{param}, err
	}
	var result []any
	for _, name := range sortedKeys(props) {
		schema, _ := deepCopy(props[name]).(map[string]any)
		flat := map[string]any{"name": name, "in": "query", "required": slices.Contains(required, name), "schema": schema}
		if description, ok := schema["description"]; ok {
			flat["description"] = description
			delete(schema, "description")
		}
		result = append(result, flat)
	}
	return result, nil
}

// objectProperties collects the properties of an object schema, following
// schema references and allOf. ok is false when the schema is not a plain object.
func (p *preparer) objectProperties(mod *module, schema any) (map[string]any, []string, bool, error) {
	s, isMap := schema.(map[string]any)
	if !isMap {
		return nil, nil, false, nil
	}
	if ref, isRef := s["$ref"].(string); isRef {
		key, err := parseRef(ref)
		if err != nil {
			return nil, nil, false, err
		}
		def, found := lookup(mod, key)
		if !found {
			return nil, nil, false, fmt.Errorf("%s: %s not found", mod.name, ref)
		}
		return p.objectProperties(mod, def)
	}
	if _, has := s["oneOf"]; has {
		return nil, nil, false, nil
	}
	if _, has := s["anyOf"]; has {
		return nil, nil, false, nil
	}
	props := map[string]any{}
	var required []string
	allOf, hasAllOf := s["allOf"].([]any)
	for _, part := range allOf {
		partProps, partRequired, ok, err := p.objectProperties(mod, part)
		if err != nil || !ok {
			return nil, nil, false, err
		}
		for k, v := range partProps {
			props[k] = v
		}
		required = append(required, partRequired...)
	}
	own, hasProps := s["properties"].(map[string]any)
	if !hasAllOf && !hasProps && s["type"] != "object" {
		return nil, nil, false, nil
	}
	for k, v := range own {
		props[k] = v
	}
	required = append(required, asStrings(s["required"])...)
	return props, required, true, nil
}

func (p *preparer) collectRefs(mod *module, v any) error {
	switch t := v.(type) {
	case map[string]any:
		if ref, ok := t["$ref"].(string); ok {
			if err := p.addRef(mod, ref); err != nil {
				return err
			}
		}
		for _, k := range sortedKeys(t) {
			if err := p.collectRefs(mod, t[k]); err != nil {
				return err
			}
		}
	case []any:
		for _, item := range t {
			if err := p.collectRefs(mod, item); err != nil {
				return err
			}
		}
	}
	return nil
}

func (p *preparer) addRef(mod *module, ref string) error {
	key, err := parseRef(ref)
	if err != nil {
		return err
	}
	def, ok := lookup(mod, key)
	if !ok {
		return fmt.Errorf("%s: %s not found", mod.name, ref)
	}
	if existing, ok := p.components[key]; ok && !reflect.DeepEqual(existing, def) {
		return fmt.Errorf("component %s is defined differently in %s and %s", key, p.origin[key], mod.name)
	} else if !ok {
		p.components[key] = def
		p.origin[key] = mod.name
	}
	visit := mod.name + "#" + key.String()
	if p.visited[visit] {
		return nil
	}
	p.visited[visit] = true
	return p.collectRefs(mod, def)
}

func parseRef(ref string) (componentKey, error) {
	rest, ok := strings.CutPrefix(ref, componentRefPrefix)
	if !ok {
		return componentKey{}, fmt.Errorf("unsupported reference %q, only local component references are supported", ref)
	}
	kind, name, ok := strings.Cut(rest, "/")
	if !ok || name == "" || strings.Contains(name, "/") {
		return componentKey{}, fmt.Errorf("unsupported reference %q", ref)
	}
	return componentKey{kind: kind, name: name}, nil
}

func lookup(mod *module, key componentKey) (any, bool) {
	components, _ := mod.doc["components"].(map[string]any)
	kind, _ := components[key.kind].(map[string]any)
	def, ok := kind[key.name]
	return def, ok
}

func deepCopy(v any) any {
	switch t := v.(type) {
	case map[string]any:
		out := make(map[string]any, len(t))
		for k, val := range t {
			out[k] = deepCopy(val)
		}
		return out
	case []any:
		out := make([]any, len(t))
		for i, val := range t {
			out[i] = deepCopy(val)
		}
		return out
	default:
		return v
	}
}

func replaceStrings(v any, f func(string) string) any {
	switch t := v.(type) {
	case map[string]any:
		out := make(map[string]any, len(t))
		for k, val := range t {
			out[k] = replaceStrings(val, f)
		}
		return out
	case []any:
		out := make([]any, len(t))
		for i, val := range t {
			out[i] = replaceStrings(val, f)
		}
		return out
	case string:
		return f(t)
	default:
		return v
	}
}

func sortedKeys(m map[string]any) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func asStrings(v any) []string {
	items, _ := v.([]any)
	var out []string
	for _, item := range items {
		if s, ok := item.(string); ok {
			out = append(out, s)
		}
	}
	return out
}
