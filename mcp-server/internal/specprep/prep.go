package specprep

import (
	"bytes"
	"fmt"
	"maps"
	"slices"
	"strings"

	"github.com/pb33f/libopenapi"
	"github.com/pb33f/libopenapi/datamodel/high/base"
	v3 "github.com/pb33f/libopenapi/datamodel/high/v3"
	"sigs.k8s.io/yaml"

	"github.com/SwissDataScienceCenter/renku/mcp-server/internal/toolspec"
)

// Output is the result of Prepare.
type Output struct {
	// Spec is the pruned OpenAPI document the MCP server serves its tools from.
	Spec []byte
	// Warnings are changes made to the upstream schemas that the user should know about.
	Warnings []string
}

type module struct {
	name  string
	model *v3.Document
}

// Prepare builds the pruned OpenAPI document with one operation per allowlisted tool. The
// operationId and description of each operation are the name and description of the tool.
// modules maps each path in cfg.Source.Modules to the raw content of that spec.
// ref is the git ref the modules were taken from and is recorded in the output.
//
// All schemas are inlined into the operations, so the output has no components
// and the modules cannot conflict with each other.
func Prepare(cfg *Config, ref string, modules map[string][]byte) (*Output, error) {
	if err := cfg.Validate(); err != nil {
		return nil, err
	}
	var mods []module
	var openapiVersion, serverURL string
	for _, name := range cfg.Source.Modules {
		raw, ok := modules[name]
		if !ok {
			return nil, fmt.Errorf("module %s was not provided", name)
		}
		doc, err := libopenapi.NewDocument(raw)
		if err != nil {
			return nil, fmt.Errorf("parsing module %s: %w", name, err)
		}
		version := doc.GetVersion()
		if !strings.HasPrefix(version, "3.1.") {
			return nil, fmt.Errorf("module %s: only OpenAPI 3.1.x is supported, got %q", name, version)
		}
		model, err := doc.BuildV3Model()
		if err != nil {
			return nil, fmt.Errorf("module %s: %w", name, err)
		}
		var url string
		if len(model.Model.Servers) > 0 {
			url = model.Model.Servers[0].URL
		}
		if openapiVersion == "" {
			openapiVersion, serverURL = version, url
		} else if url != serverURL {
			return nil, fmt.Errorf("module %s: server url %q differs from %q", name, url, serverURL)
		}
		mods = append(mods, module{name: name, model: &model.Model})
	}

	paths := map[string]any{}
	var warnings []string
	for _, t := range cfg.Tools {
		warn := func(w string) { warnings = append(warnings, fmt.Sprintf("tool %s: %s", t.Name, w)) }
		op, err := operation(mods, t, warn)
		if err != nil {
			return nil, fmt.Errorf("tool %s (%s %s): %w", t.Name, t.Method, t.Path, err)
		}
		item, _ := paths[t.Path].(map[string]any)
		if item == nil {
			item = map[string]any{}
			paths[t.Path] = item
		}
		item[t.Method] = op
	}

	body, err := yaml.Marshal(map[string]any{
		"openapi": openapiVersion,
		"info": map[string]any{
			"title":       "Renku Data Services API (MCP subset)",
			"description": "Allowlisted subset of the Renku Data Services API exposed through the Renku MCP server.",
			"version":     ref,
		},
		"servers": []any{map[string]any{"url": serverURL}},
		"paths":   paths,
	})
	if err != nil {
		return nil, err
	}
	var spec bytes.Buffer
	fmt.Fprintf(&spec, "# Code generated by specprep from %s@%s. DO NOT EDIT.\n", cfg.Source.Repository, ref)
	spec.WriteString("# Edit apispec/tools.yaml and run 'just update-spec <ref>' instead.\n")
	spec.Write(body)

	if _, err := toolspec.Load(spec.Bytes()); err != nil {
		return nil, fmt.Errorf("the MCP server cannot serve the generated spec: %w", err)
	}
	return &Output{Spec: spec.Bytes(), Warnings: warnings}, nil
}

// operation builds the operation of a tool for the output spec.
func operation(mods []module, t Tool, warn func(string)) (map[string]any, error) {
	var found string
	var item *v3.PathItem
	var op *v3.Operation
	for _, m := range mods {
		if m.model.Paths == nil {
			continue
		}
		pathItem, ok := m.model.Paths.PathItems.Get(t.Path)
		if !ok {
			continue
		}
		o, ok := pathItem.GetOperations().Get(t.Method)
		if !ok {
			continue
		}
		if found != "" {
			return nil, fmt.Errorf("operation is defined in both %s and %s", found, m.name)
		}
		found, item, op = m.name, pathItem, o
	}
	if op == nil {
		return nil, fmt.Errorf("operation not found in any module")
	}

	params, err := parameters(slices.Concat(item.Parameters, op.Parameters))
	if err != nil {
		return nil, err
	}
	for name, description := range t.Parameters {
		i := slices.IndexFunc(params, func(p map[string]any) bool { return p["name"] == name })
		if i < 0 {
			return nil, fmt.Errorf("parameter override %q does not match any parameter", name)
		}
		params[i]["description"] = description
	}
	for _, p := range params {
		p["schema"] = clean(p["schema"].(map[string]any), "parameter "+p["name"].(string), warn)
	}

	out := map[string]any{
		"operationId": t.Name,
		"description": strings.TrimSpace(t.Description),
		// The tools forward the raw responses, so the response schemas are not needed.
		"responses": map[string]any{"default": map[string]any{"description": "The response of the Renku API."}},
	}
	if len(params) > 0 {
		out["parameters"] = params
	}
	if rb := op.RequestBody; rb != nil {
		if rb.Content == nil {
			return nil, fmt.Errorf("request body has no content")
		}
		media, ok := rb.Content.Get("application/json")
		if !ok {
			return nil, fmt.Errorf("request body: only application/json is supported")
		}
		schema, err := inline(media.Schema)
		if err != nil {
			return nil, fmt.Errorf("request body: %w", err)
		}
		schema = clean(schema, "body", warn)
		body := map[string]any{"content": map[string]any{"application/json": map[string]any{"schema": schema}}}
		if rb.Description != "" {
			body["description"] = rb.Description
		}
		if rb.Required != nil && *rb.Required {
			body["required"] = true
		}
		out["requestBody"] = body
	}
	return out, nil
}

// parameters merges path level and operation level parameters and flattens
// exploded object query parameters into one argument per property.
func parameters(all []*v3.Parameter) ([]map[string]any, error) {
	var merged []*v3.Parameter
	for _, p := range all {
		// Operation level parameters override path level ones with the same name and location.
		merged = slices.DeleteFunc(merged, func(m *v3.Parameter) bool { return m.Name == p.Name && m.In == p.In })
		merged = append(merged, p)
	}
	var result []map[string]any
	for _, p := range merged {
		if p.Schema == nil {
			return nil, fmt.Errorf("parameter %s: only parameters with a schema are supported", p.Name)
		}
		schema, err := inline(p.Schema)
		if err != nil {
			return nil, fmt.Errorf("parameter %s: %w", p.Name, err)
		}
		exploded := (p.Style == "" || p.Style == "form") && (p.Explode == nil || *p.Explode)
		if p.In == "query" && exploded {
			if props, required, ok := objectProperties(schema); ok {
				// One parameter per property is equivalent on the wire.
				for _, name := range slices.Sorted(maps.Keys(props)) {
					prop, _ := props[name].(map[string]any)
					flat := map[string]any{"name": name, "in": "query", "required": slices.Contains(required, name), "schema": prop}
					if description, ok := prop["description"]; ok {
						flat["description"] = description
						delete(prop, "description")
					}
					result = append(result, flat)
				}
				continue
			}
		}
		param := map[string]any{"name": p.Name, "in": p.In, "schema": schema}
		if p.Description != "" {
			param["description"] = p.Description
		}
		if p.Required != nil && *p.Required {
			param["required"] = true
		}
		if p.Style != "" {
			param["style"] = p.Style
		}
		if p.Explode != nil {
			param["explode"] = *p.Explode
		}
		result = append(result, param)
	}
	return result, nil
}

// objectProperties collects the properties of an object schema, including
// those of its allOf parts. ok is false when the schema is not a plain object.
func objectProperties(s map[string]any) (props map[string]any, required []string, ok bool) {
	if s["oneOf"] != nil || s["anyOf"] != nil {
		return nil, nil, false
	}
	props = map[string]any{}
	allOf, hasAllOf := s["allOf"].([]any)
	for _, part := range allOf {
		partMap, _ := part.(map[string]any)
		partProps, partRequired, ok := objectProperties(partMap)
		if !ok {
			return nil, nil, false
		}
		maps.Copy(props, partProps)
		required = append(required, partRequired...)
	}
	own, hasProps := s["properties"].(map[string]any)
	if !hasAllOf && !hasProps && s["type"] != "object" {
		return nil, nil, false
	}
	maps.Copy(props, own)
	ownRequired, _ := s["required"].([]any)
	for _, r := range ownRequired {
		if name, ok := r.(string); ok {
			required = append(required, name)
		}
	}
	return props, required, true
}

// inline renders a schema with all references resolved.
func inline(proxy *base.SchemaProxy) (map[string]any, error) {
	schema, err := proxy.BuildSchema()
	if err != nil {
		return nil, err
	}
	raw, err := schema.RenderInline()
	if err != nil {
		return nil, err
	}
	var out map[string]any
	if err := yaml.Unmarshal(raw, &out); err != nil {
		return nil, err
	}
	// libopenapi keeps the reference that closes a cycle.
	if ref := findRef(out); ref != "" {
		return nil, fmt.Errorf("recursive schema %s cannot be inlined", ref)
	}
	return out, nil
}

func findRef(v any) string {
	switch t := v.(type) {
	case map[string]any:
		if ref, ok := t["$ref"].(string); ok {
			return ref
		}
		for _, val := range t {
			if ref := findRef(val); ref != "" {
				return ref
			}
		}
	case []any:
		for _, val := range t {
			if ref := findRef(val); ref != "" {
				return ref
			}
		}
	}
	return ""
}
